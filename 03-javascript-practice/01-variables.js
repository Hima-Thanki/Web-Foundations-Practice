// 1. Using let
let name = "Hima";
let age = 24;

// 2. Using const
const country = "India";

// 3. Display values in the console
console.log("My name is:", name);
console.log("My age is:", age);
console.log("My country is:", country);

// 4. Update a variable declared with let
age = 25;
console.log("Updated age:", age);
